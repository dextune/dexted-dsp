#!/usr/bin/env python3
"""Deterministic, application-shaped *synthetic* filter-design catalog.

Reimplements selected W3C Audio EQ Cookbook biquad formulae.  Not actual
production device telemetry and not an indicator of product defect rates.
The exported coefficient values, not the ideal design parameters, are the
subject of certification. No third-party dependency is required.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import random
import struct
from pathlib import Path

SCHEMA = 'dexted-dsp/eq-design-catalog/v1'
REFERENCE = 'https://www.w3.org/TR/2021/NOTE-audio-eq-cookbook-20210608/'
FAMILIES = ('peaking', 'notch', 'lowpass', 'highpass')
DEFAULT_SEED = 20261008
DEFAULT_COUNT = 1200


def f32(value: float) -> float:
    """Round via IEEE-754 binary32; fail on NaN/Inf and overflow."""
    if not math.isfinite(value):
        raise ValueError('non-finite designed coefficient')
    try:
        v = struct.unpack('!f', struct.pack('!f', value))[0]
    except OverflowError as exc:
        raise ValueError('coefficient cannot be represented as float32') from exc
    if not math.isfinite(v):
        raise ValueError('coefficient overflows binary32')
    return v


def design_biquad(kind: str, fs: int, f0: float, q: float,
                  gain_db: float = 0.) -> list[float]:
    """Return normalized SOS row in represented float32, including exact a0=1.

    All inputs are deterministic *design parameters*, not measured signals.
    RBJ/W3C formulae use the Q interpretation specific to peaking EQ.
    """
    if kind not in FAMILIES or not (fs > 0 and 0 < f0 < fs / 2 and q > 0):
        raise ValueError('invalid audio EQ design parameters')
    if not all(math.isfinite(x) for x in (f0, q, gain_db)):
        raise ValueError('non-finite audio EQ design parameters')
    w = 2 * math.pi * f0 / fs
    cosine, alpha = math.cos(w), math.sin(w) / (2 * q)
    a0, a1, a2 = 1 + alpha, -2 * cosine, 1 - alpha
    if kind == 'peaking':
        A = 10 ** (gain_db / 40)
        b0, b1, b2 = 1 + alpha * A, -2 * cosine, 1 - alpha * A
        a0, a1, a2 = 1 + alpha / A, -2 * cosine, 1 - alpha / A
    elif kind == 'notch':
        b0, b1, b2 = 1, -2 * cosine, 1
    elif kind == 'lowpass':
        b0, b1, b2 = (1-cosine)/2, 1-cosine, (1-cosine)/2
    else:
        b0, b1, b2 = (1+cosine)/2, -(1+cosine), (1+cosine)/2
    return [f32(b0/a0), f32(b1/a0), f32(b2/a0), 1.0,
            f32(a1/a0), f32(a2/a0)]


def generate(*, count: int = DEFAULT_COUNT, seed: int = DEFAULT_SEED) -> dict:
    if not 4 <= count <= 10000 or type(seed) is not int:
        raise ValueError('count must be [4,10000], seed integer')
    rng = random.Random(seed)
    cases = []
    for i in range(count):
        # The same four families and their mixtures are predeclared by position.
        # Alternate single sections and two-section chains to bound exact oracle cost.
        primary = FAMILIES[i % 4]
        nsec = 1 if i % 5 < 3 else 2
        sections, specifications = [], []
        for j in range(nsec):
            kind = primary if j == 0 else FAMILIES[(i//4 + j) % 4]
            fs = 48000
            f0 = round(2 ** rng.uniform(math.log2(80.),math.log2(16000.)), 6)
            q = round(2 ** rng.uniform(math.log2(.55),math.log2(12.)),6)
            db = round(rng.uniform(-9., 9.), 4) if kind == 'peaking' else 0.
            sections.append(design_biquad(kind, fs, f0, q, db))
            specifications.append({'type':kind, 'f0_hz':f0, 'q':q, 'gain_db':db})
        key = f'eq-{i:04d}-{primary}-{nsec}s'
        split = 'holdout' if hashlib.sha256(key.encode('ascii')).digest()[0] < 64 else 'development'
        cases.append({'id':key,'family':primary,'sections':nsec,'sample_rate_hz':48000,
                      'design':specifications,'precision':'float32',
                      'max_gain':(1.005 if primary != 'peaking' else 1.3),
                      'sos':sections,'split':split})
    return {'schema':SCHEMA, 'type':'application-shaped synthetic DSP coefficients',
            'NOT_real_world_data':True, 'seed':seed, 'count':count,
            'source_reference':REFERENCE,
            'binary32_rounding':'struct.pack !f then unpack !f, a0 normalized before rounding',
            'holdout_rule':'SHA256(case_id).first_byte < 64; chosen without observing results',
            'cases':cases}


def canonical_bytes(obj: dict) -> bytes:
    return (json.dumps(obj,sort_keys=True,separators=(',',':'),allow_nan=False)+'\n').encode('utf-8')


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--count', type=int,default=DEFAULT_COUNT)
    p.add_argument('--seed', type=int,default=DEFAULT_SEED)
    p.add_argument('--out',type=Path)
    p.add_argument('--check-sha256',help='Fail unless generated byte SHA256 matches expected')
    args = p.parse_args()
    data = canonical_bytes(generate(count=args.count,seed=args.seed))
    digest = hashlib.sha256(data).hexdigest()
    if args.check_sha256 and digest != args.check_sha256:
        raise SystemExit(f'catalog SHA256 mismatch: actual {digest}, expected {args.check_sha256}')
    if args.out:
        if args.out.exists():
            raise SystemExit('refusing to overwrite existing catalog: '+str(args.out))
        args.out.parent.mkdir(parents=True,exist_ok=True)
        args.out.write_bytes(data)
    print(json.dumps({'status':'passed', 'cases':args.count,'seed':args.seed,'sha256':digest,
                      'output':str(args.out) if args.out else None}))


if __name__ == '__main__':
    main()
